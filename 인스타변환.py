# 매장 사진을 인스타그램용 1080x1080 정사각형으로 바꿔 주는 프로그램
#
# - '자료' 폴더의 jpg, png 사진을 모두 읽는다 (원본은 절대 바꾸지 않음)
# - 사진 가운데를 기준으로 정사각형으로 잘라서 찌그러지지 않게 한다
# - '완성' 폴더에 '오늘날짜_01.jpg' 형식으로 저장한다
# - 로고 파일이 있으면 오른쪽 아래에 흰 테두리 + 반투명 바탕과 함께 작게 넣는다
# - '가게정보.txt'를 읽어서 인스타그램 문구 3가지를 '완성/홍보문구.txt'로 저장한다

import re
from datetime import date
from pathlib import Path

from PIL import Image, ImageChops, ImageDraw, ImageOps

크기 = 1080
사진_종류 = {".jpg", ".jpeg", ".png"}

# 로고 설정
로고_비율 = 0.15      # 로고 가로 폭 = 사진 가로 폭의 15%
로고_여백 = 40        # 흰 네모가 사진 가장자리에서 떨어지는 거리(픽셀)
로고_안쪽여백 = 12    # 로고 둘레에 남기는 바탕 두께(픽셀)
로고_바탕_진하기 = 0.5  # 바탕 흰색의 진하기 (1 = 완전 흰색, 0 = 완전 투명)
로고_테두리_두께 = 3    # 네모 둘레 흰 선의 두께(픽셀)

# 이 파일이 있는 폴더를 기준으로 '자료', '완성' 폴더를 찾는다
기본_폴더 = Path(__file__).resolve().parent
자료_폴더 = 기본_폴더 / "자료"
완성_폴더 = 기본_폴더 / "완성"

# 로고는 이 순서대로 찾는다: 로고.jpg가 없으면 로고.png를 쓴다
로고_후보 = [
    기본_폴더 / "로고.jpg",
    자료_폴더 / "로고.jpg",
    기본_폴더 / "로고.png",
    자료_폴더 / "로고.png",
]


def 다음_번호(오늘):
    """오늘 이미 만든 파일이 있으면 그 다음 번호부터 쓴다 (덮어쓰기 방지)"""
    번호들 = []
    for 파일 in 완성_폴더.glob(f"{오늘}_*.jpg"):
        뒷부분 = 파일.stem.split("_")[-1]
        if 뒷부분.isdigit():
            번호들.append(int(뒷부분))
    return max(번호들, default=0) + 1


def 정사각형_만들기(원본_경로):
    with Image.open(원본_경로) as 사진:
        # 휴대폰 사진이 옆으로 누워 보이지 않도록 원래 방향으로 돌린다
        사진 = ImageOps.exif_transpose(사진)

        # 투명한 부분(로고 등)은 검게 나오지 않도록 흰 바탕을 깐다
        if 사진.mode in ("RGBA", "LA") or (사진.mode == "P" and "transparency" in 사진.info):
            사진 = 사진.convert("RGBA")
            흰바탕 = Image.new("RGB", 사진.size, (255, 255, 255))
            흰바탕.paste(사진, mask=사진.getchannel("A"))
            사진 = 흰바탕
        else:
            사진 = 사진.convert("RGB")

        # 가운데를 기준으로 정사각형으로 자르고 1080x1080으로 맞춘다
        return ImageOps.fit(사진, (크기, 크기), method=Image.LANCZOS, centering=(0.5, 0.5))


def 로고_불러오기():
    """로고 파일을 찾아서 흰 네모 바탕까지 입힌 '로고 도장'을 만든다. 없으면 None"""
    로고_경로 = next((p for p in 로고_후보 if p.is_file()), None)
    if 로고_경로 is None:
        return None

    try:
        with Image.open(로고_경로) as 로고:
            로고 = ImageOps.exif_transpose(로고).convert("RGBA")
    except Exception as 오류:
        print(f"로고 파일을 열 수 없어서 로고 없이 만들어요: {로고_경로.name} ({오류})")
        return None

    # 로고 둘레의 투명하거나 하얀 빈 공간을 잘라내서 로고 그림만 남긴다
    흰바탕 = Image.new("RGBA", 로고.size, (255, 255, 255, 255))
    합친것 = Image.alpha_composite(흰바탕, 로고).convert("L")
    그림_영역 = 합친것.point(lambda 밝기: 255 if 밝기 < 245 else 0).getbbox()
    if 그림_영역:
        로고 = 로고.crop(그림_영역)
        합친것 = 합친것.crop(그림_영역)

    # 로고에 칠해진 하얀 바탕을 투명하게 만든다 (거의 흰색인 부분만, 연한 김 색깔은 남김)
    흰색_지우기 = 합친것.point(lambda 밝기: 0 if 밝기 >= 250 else (255 if 밝기 < 235 else int((250 - 밝기) / 15 * 255)))
    로고.putalpha(ImageChops.multiply(로고.getchannel("A"), 흰색_지우기))

    # 가로 폭을 사진의 15%로 맞추고, 세로는 같은 비율로 줄인다 (찌그러짐 방지)
    로고_폭 = round(크기 * 로고_비율)
    로고_높이 = round(로고.height * 로고_폭 / 로고.width)
    로고 = 로고.resize((로고_폭, 로고_높이), Image.LANCZOS)

    # 로고 둘레에 여유를 두고, 흰 테두리 선 + 반투명 흰 바탕 네모를 만든다
    네모_폭 = 로고_폭 + 로고_안쪽여백 * 2
    네모_높이 = 로고_높이 + 로고_안쪽여백 * 2
    도장 = Image.new("RGBA", (네모_폭, 네모_높이), (0, 0, 0, 0))
    ImageDraw.Draw(도장).rectangle(
        [0, 0, 네모_폭 - 1, 네모_높이 - 1],
        fill=(255, 255, 255, round(255 * 로고_바탕_진하기)),
        outline=(255, 255, 255, 255),
        width=로고_테두리_두께,
    )
    도장.alpha_composite(로고, (로고_안쪽여백, 로고_안쪽여백))

    print(f"로고 사용: {로고_경로.relative_to(기본_폴더)}")
    return 도장


def 로고_붙이기(사진, 도장):
    """반투명 로고 네모를 오른쪽 아래, 가장자리에서 40픽셀 안쪽에 겹쳐 놓는다"""
    x = 사진.width - 로고_여백 - 도장.width
    y = 사진.height - 로고_여백 - 도장.height
    겹친것 = 사진.convert("RGBA")
    겹친것.alpha_composite(도장, (x, y))
    return 겹친것.convert("RGB")


def 사진_만들기():
    사진들 = sorted(f for f in 자료_폴더.iterdir() if f.is_file() and f.suffix.lower() in 사진_종류)
    if not 사진들:
        print("'자료' 폴더에 jpg, png 사진이 없어요.")
        return

    도장 = 로고_불러오기()
    if 도장 is None:
        print("로고 파일이 없어서 로고 없이 만들어요.")

    오늘 = date.today().strftime("%Y%m%d")
    번호 = 다음_번호(오늘)
    성공 = 0

    for 원본 in 사진들:
        try:
            결과 = 정사각형_만들기(원본)
        except Exception as 오류:
            print(f"  건너뜀: {원본.name} (사진을 열 수 없어요: {오류})")
            continue

        if 도장 is not None:
            결과 = 로고_붙이기(결과, 도장)

        저장_경로 = 완성_폴더 / f"{오늘}_{번호:02d}.jpg"
        결과.save(저장_경로, "JPEG", quality=95)
        print(f"  완료: {원본.name}  →  완성/{저장_경로.name}")
        번호 += 1
        성공 += 1

    print(f"\n총 {성공}장을 인스타그램용으로 만들었어요. '완성' 폴더를 확인하세요!")


