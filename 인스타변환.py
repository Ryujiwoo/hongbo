def 글자_읽기(경로):
    """메모장에서 저장한 방식이 달라도 읽을 수 있게 두 가지 방식으로 시도한다"""
    for 방식 in ("utf-8-sig", "cp949"):
        try:
            return 경로.read_text(encoding=방식)
        except UnicodeDecodeError:
            continue
    return 경로.read_text(encoding="utf-8", errors="ignore")


def 가게정보_읽기(경로):
    """'항목: 내용' 줄과 '이번 주 홍보할 것' 아래의 '- ' 줄을 골라낸다"""
    정보 = {}
    홍보들 = []
    for 줄 in 글자_읽기(경로).splitlines():
        줄 = 줄.strip()
        if 줄.startswith("-"):
            홍보들.append(줄.lstrip("-").strip())
        elif ":" in 줄:
            항목, 내용 = 줄.split(":", 1)
            if 내용.strip():
                정보[항목.strip()] = 내용.strip()
    return 정보, 홍보들


def 쉼표로_나누기(글):
    """'5,500원'처럼 숫자 속 쉼표는 두고, '쉼표+띄어쓰기'에서만 나눈다"""
    return [조각.strip() for 조각 in re.split(r",\s+", 글) if 조각.strip()]


def 존댓말로(글):
    """'넣음', '달지 않음', '할인' 같은 메모 말투를 '~습니다' 문장으로 바꾼다"""
    글 = 글.strip().rstrip(".")
    if not 글:
        return ""
    if 글.endswith(("할인", "증정", "제공")):
        return 글 + "해 드립니다."
    if 글.endswith(("사용", "운영", "진행", "판매", "준비", "오픈", "시작", "마감", "예정")):
        return 글 + ("입니다." if 글.endswith("예정") else "합니다.")
    if 글.endswith("음"):
        return 글[:-1] + "습니다."
    끝 = 글[-1]
    if "가" <= 끝 <= "힣" and (ord(끝) - 0xAC00) % 28 == 16:  # 받침이 'ㅁ'인 글자 (함, 됨, 임 …)
        return 글[:-1] + chr(ord(끝) - 16 + 17) + "니다."   # 'ㅁ' 받침을 'ㅂ'으로 → 합니다, 됩니다, 입니다
    return 글 + "입니다."


def 을를(낱말):
    """받침이 있으면 '을', 없으면 '를'을 붙인다 (예: 라떼를, 케이크를, 빙수를, 크림빵을)"""
    끝 = 낱말[-1] if 낱말 else ""
    받침 = "가" <= 끝 <= "힣" and (ord(끝) - 0xAC00) % 28 != 0
    return 낱말 + ("을" if 받침 else "를")


def 홍보_나누기(홍보들):
    """홍보 줄들을 '신메뉴'와 '할인·이벤트'와 '그 밖의 소식'으로 나눈다"""
    메뉴들, 할인들, 기타 = [], [], []
    for 홍보 in 홍보들:
        조각들 = 쉼표로_나누기(홍보)
        이름 = re.search(r"['‘’\"“”]([^'‘’\"“”]+)['‘’\"“”]", 홍보)
        if 이름 or "신메뉴" in 홍보:
            가격 = re.search(r"\d[\d,]*원", 조각들[0])
            메뉴_이름 = 이름.group(1) if 이름 else re.sub(r"신메뉴|\d[\d,]*원", "", 조각들[0]).strip()
            메뉴들.append({
                "이름": 메뉴_이름,
                "가격": 가격.group(0) if 가격 else "",
                "설명": " ".join(존댓말로(조각) for 조각 in 조각들[1:]),
            })
        elif any(낱말 in 홍보 for 낱말 in ("할인", "이벤트", "증정", "무료", "1+1")):
            할인들.append(홍보)
        else:
            기타.append(홍보)
    return 메뉴들, 할인들, 기타


def 해시태그_만들기(정보, 메뉴들):
    """지역명 + 업종 + 메뉴를 조합해 해시태그 10개를 만든다"""
    낱말들 = 정보.get("위치", "").split()
    지역들 = []
    if 낱말들:
        지역들.append(낱말들[0])                                   # 광주
        if len(낱말들) > 1 and 낱말들[1].endswith(("구", "군", "시")):
            지역들.append(낱말들[0] + 낱말들[1])                    # 광주북구
        동네 = [w for w in 낱말들[1:] if w != "지구" and not w.endswith(("구", "군", "시"))]
        if 동네:
            지역들.append(동네[-1])                                # 비엔날레

    가게_글 = 정보.get("가게 이름", "") + 정보.get("가게 특징", "")
    if "커피" in 가게_글 or "카페" in 가게_글:
        업종들 = ["카페", "커피"]
    else:
        업종들 = [정보.get("가게 이름", "가게").split()[-1]]

    메뉴_태그 = [m["이름"].replace(" ", "") for m in 메뉴들 if m["이름"]]

    후보 = []
    후보 += [지역 + 업종들[0] for 지역 in 지역들]                      # 광주카페, 광주북구카페, 비엔날레카페
    if len(업종들) > 1 and 지역들:
        후보 += [지역들[0] + 업종들[1], 지역들[-1] + 업종들[1]]        # 광주커피, 비엔날레커피
    후보 += 메뉴_태그                                                  # 흑임자라떼
    if 지역들:
        후보 += [지역들[0] + 메뉴 for 메뉴 in 메뉴_태그]               # 광주흑임자라떼
    if 정보.get("가게 이름"):
        후보.append(정보["가게 이름"].replace(" ", ""))                # 브릿지커피
    if 메뉴_태그:
        후보.append(업종들[0] + "신메뉴")                              # 카페신메뉴
    if "스페셜티" in 정보.get("가게 특징", ""):
        후보.append("스페셜티커피")
    후보 += [지역 + 업종 for 업종 in 업종들 for 지역 in 지역들]        # 남은 칸 채우기용
    후보 += [업종 + "추천" for 업종 in 업종들] + ["오늘의" + 업종들[0]]
    후보 += [지역 + "맛집" for 지역 in 지역들] + [업종들[0] + "스타그램"]

    태그들 = []
    for 태그 in 후보:
        if 태그 and 태그 not in 태그들:
            태그들.append(태그)
    return " ".join("#" + 태그 for 태그 in 태그들[:10])


def 문장들(글):
    """'A입니다. B입니다.'를 한 문장씩 나눈다"""
    return [조각.strip() for 조각 in re.split(r"(?<=[.])\s+", 글) if 조각.strip()]


def 줄_나누기(문장, 기준=22):
    """긴 문장은 사장님 글처럼 '~하시면 / ~는데' 뒤에서 두 줄로 나눈다"""
    if len(문장) <= 기준:
        return [문장]
    for 끊을곳 in ("하시면 ", "오시면 ", "는데 ", "지만 "):
        위치 = 문장.find(끊을곳)
        if 0 < 위치 < len(문장) - len(끊을곳) - 2:
            자를곳 = 위치 + len(끊을곳)
            return [문장[:자를곳].rstrip(" ,"), 문장[자를곳:]]
    return [문장]


def 문단_합치기(문단들):
    """문장 목록들을 '한 문장 한 줄 + 문단 사이 빈 줄' 모양으로 만든다"""
    결과 = []
    for 문단 in 문단들:
        줄들 = []
        for 문장 in 문단:
            줄들 += 줄_나누기(문장)
        if 줄들:
            결과.append("\n".join(줄들))
    return "\n\n".join(결과)


def 가게_재료(정보, 메뉴들, 할인들, 기타):
    """세 채널이 같이 쓰는 재료(가게 이름, 메뉴 문장, 할인 문장 …)를 미리 만들어 둔다"""
    이름 = 정보.get("가게 이름", "저희 가게")
    가게_글 = 이름 + 정보.get("가게 특징", "")
    if "커피" in 가게_글 or "카페" in 가게_글:
        대표 = "☕"
    elif "빵" in 가게_글 or "베이커리" in 가게_글:
        대표 = "🥐"
    else:
        대표 = "🙂"
    return {
        "이름": 이름,
        "위치": 정보.get("위치", ""),
        "고객층": 정보.get("주 고객층", ""),
        "특징들": 쉼표로_나누기(정보.get("가게 특징", "")),
        "대표": 대표,
        "할인": [존댓말로(할인.replace(" 방문 시 ", " 방문하시면 ")) for 할인 in 할인들],
        "기타": [존댓말로(글) for 글 in 기타],
        "메뉴": 메뉴들[0] if 메뉴들 else None,
        "메뉴들": 메뉴들,
    }


def 문구_틀_채우기(정보, 메뉴들, 할인들, 기타):
    """인스타그램용 감성형 / 정보형 / 이벤트형 (사장님 말투: 짧은 문장, 한 줄에 한 문장, 이모지는 끝에 하나)"""
    재 = 가게_재료(정보, 메뉴들, 할인들, 기타)
    메뉴 = 재["메뉴"]
    끝인사 = f"{재['위치']}, {재['이름']}입니다." if 재["위치"] else f"{재['이름']}입니다."

    # 감성형: 메뉴 이야기를 담담하게
    감성 = []
    if 메뉴:
        감성.append([f"{을를(메뉴['이름'])} 새로 냈습니다."])
        감성.append(문장들(메뉴["설명"]))
    감성 += [[글] for 글 in 재["기타"]]
    감성.append(재["할인"])
    감성.append([f"{끝인사} {재['대표']}"])

    # 정보형: 가격과 할인을 차례대로
    정보형 = [["이번 주 안내드립니다."]]
    for m in 재["메뉴들"]:
        가격 = f", {m['가격']}입니다." if m["가격"] else "입니다."
        정보형.append([f"신메뉴 {m['이름']}{가격}"] + 문장들(m["설명"]))
    정보형.append(재["할인"] + 재["기타"])
    if 재["위치"]:
        정보형.append([f"{재['이름']}, {재['위치']}에 있습니다. {재['대표']}"])
    else:
        정보형.append([f"{재['이름']}입니다. {재['대표']}"])

    # 이벤트형: 할인을 먼저, 없으면 이번 주 소식을 먼저
    이벤트 = []
    if 재["할인"]:
        이벤트.append(재["할인"])
    이벤트.append(재["기타"])
    if 메뉴:
        뒤 = "도" if 재["할인"] else 을를(메뉴["이름"])[-1]
        가격 = [f"{메뉴['가격']}입니다."] if 메뉴["가격"] else []
        이벤트.append([f"{메뉴['이름']}{뒤} 새로 냈습니다."] + 가격 + 문장들(메뉴["설명"]))
    이벤트.append(["미리 말씀드립니다.", f"{끝인사} {재['대표']}"])

    return {
        "감성형": 문단_합치기(감성),
        "정보형": 문단_합치기(정보형),
        "이벤트형": 문단_합치기(이벤트),
    }


def 은는(낱말):
    """받침이 있으면 '은', 없으면 '는'을 붙인다 (예: 브릿지 커피는, 달빛 베이커리는)"""
    끝 = 낱말[-1] if 낱말 else ""
    받침 = "가" <= 끝 <= "힣" and (ord(끝) - 0xAC00) % 28 != 0
    return 낱말 + ("은" if 받침 else "는")


def 블로그_문구(정보, 메뉴들, 할인들, 기타):
    """네이버 블로그용: 1000자 안팎, 해시태그·이모지 없이, 짧은 문장을 줄 바꿔 이어 쓴다"""
    재 = 가게_재료(정보, 메뉴들, 할인들, 기타)
    이름, 위치 = 재["이름"], 재["위치"]

    제목_메뉴 = f" - {메뉴들[0]['이름']}" if 메뉴들 else ""
    문단들 = []

    # 인사
    인사 = [f"안녕하세요. {이름}입니다."]
    if 위치:
        인사.append(f"{위치}에서 가게를 하고 있습니다.")
    인사 += ["이번 주에 달라진 것들을 정리해 두려고 합니다.",
             "가게에서 다 말씀드리기 어려운 것들을 여기에는 조금 더 자세히 적습니다."]
    문단들.append(인사)

    # 가게 소개 (특징은 메모 그대로 목록으로)
    if 재["특징들"] or 재["고객층"]:
        소개 = ["처음 오시는 분들을 위해 가게 소개를 조금 적습니다."]
        소개 += [f"· {특징}" for 특징 in 재["특징들"]]
        문단들.append(소개)
        뒷말 = [f"찾아 주시는 분들은 주로 {재['고객층']}입니다."] if 재["고객층"] else []
        뒷말 += ["크게 꾸민 곳은 아닙니다.", "대신 하나를 내더라도 신경 써서 준비하려고 합니다.",
                 "기본에 충실한 가게가 되고 싶습니다."]
        문단들.append(뒷말)

    # 신메뉴
    for 메뉴 in 메뉴들:
        글 = [f"이번 주에는 {을를(메뉴['이름'])} 새로 냈습니다."]
        if 메뉴["가격"]:
            글.append(f"가격은 {메뉴['가격']}입니다.")
        문단들.append(글)
        if 메뉴["설명"]:
            문단들.append(["처음 보시는 메뉴일 수 있어서 조금 더 설명드립니다."] + 문장들(메뉴["설명"]))
        문단들.append(["새 메뉴는 당분간 조금씩 손보면서 맞춰 가려고 합니다.",
                       "드셔 보시고 느낀 점을 말씀해 주시면 참고하겠습니다."])

    # 할인과 그 밖의 소식
    if 재["할인"]:
        문단들.append(["그리고 이번 주에는 작은 혜택이 있습니다."] + 재["할인"])
        문단들.append(["큰 혜택은 아니지만 미리 말씀드립니다.", "시간이 맞으시는 분들은 참고해 주세요."])
    if 재["기타"]:
        문단들.append(["그 밖에 알려 드릴 것도 있습니다."] + 재["기타"])

    # 위치와 맺음말
    if 위치:
        문단들.append([f"{은는(이름)} {위치}에 있습니다.", "근처에 오실 일이 있으면 참고해 주세요."])
    # 한눈에 정리
    정리 = ["글이 조금 길어져서 한 번에 정리해 둡니다."]
    정리 += [f"· 신메뉴: {m['이름']} {m['가격']}".rstrip() for m in 메뉴들]
    정리 += [f"· 혜택: {할인}" for 할인 in 할인들]
    정리 += [f"· 알림: {글}" for 글 in 기타]
    if 위치:
        정리.append(f"· 위치: {위치}")
    if len(정리) > 1:
        문단들.append(정리)

    문단들.append(["가격과 할인 내용은 이번 주 기준입니다.", "바뀌는 것이 생기면 다시 말씀드리겠습니다.",
                   "궁금하신 점은 가게에서 편하게 물어봐 주세요."])
    문단들.append(["이번 주 소식은 여기까지입니다.",
                   "늘 찾아 주시는 손님들께 감사드립니다.",
                   "읽어 주셔서 감사합니다."])
    문단들.append([f"{이름} 드림"])

    return f"[{이름}] 이번 주 안내{제목_메뉴}\n\n" + 문단_합치기(문단들)


def 카톡_문구(정보, 메뉴들, 할인들, 기타):
    """카카오톡 단골 공지용: 3줄 이내, 존댓말, 이모지 없이"""
    이름 = 정보.get("가게 이름", "저희 가게")
    소식 = [f"신메뉴 {m['이름']} {m['가격']}".rstrip() for m in 메뉴들]
    소식 += [할인.replace("이전 방문 시 ", "이전 ") for 할인 in 할인들]
    소식 += 기타
    줄들 = [f"{이름}입니다. 이번 주 안내드립니다."]
    if 소식:
        줄들.append(" / ".join(소식))
    줄들.append("미리 말씀드립니다.")
    return "\n".join(줄들)


def 문구_만들기():
    가게정보_경로 = next((p for p in 가게정보_후보 if p.is_file()), None)
    if 가게정보_경로 is None:
        print("\n'가게정보.txt' 파일이 없어서 홍보 문구는 건너뛰어요.")
        return

    정보, 홍보들 = 가게정보_읽기(가게정보_경로)
    메뉴들, 할인들, 기타 = 홍보_나누기(홍보들)
    문구들 = 문구_틀_채우기(정보, 메뉴들, 할인들, 기타)
    해시태그 = 해시태그_만들기(정보, 메뉴들)

    블로그 = 블로그_문구(정보, 메뉴들, 할인들, 기타)
    카톡 = 카톡_문구(정보, 메뉴들, 할인들, 기타)

    선 = "=" * 40
    내용 = [f"홍보 문구  ({date.today():%Y-%m-%d} 만듦)", ""]

    내용 += [선, "[인스타그램용]", 선, ""]
    for 종류, 문구 in 문구들.items():
        내용 += [f"--- {종류} ---", 문구, "", 해시태그, ""]

    내용 += [선, f"[네이버 블로그용]  ({len(블로그)}자)", 선, "", 블로그, ""]
    내용 += [선, "[카카오톡 단골 공지용]", 선, "", 카톡, ""]

    문구_파일.write_text("\n".join(내용), encoding="utf-8")

    print(f"\n홍보 문구를 만들었어요: 인스타그램 3가지 + 블로그 + 카카오톡 ({가게정보_경로.name} 참고)  →  완성/{문구_파일.name}")


